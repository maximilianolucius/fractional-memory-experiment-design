#!/usr/bin/env python3
"""Export manuscript macros from archived JSON results.

This prevents hand-copied benchmark numbers from drifting away from the
machine-readable artifacts. It does not recompute the benchmark.
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmark" / "results"
OUT = ROOT / "sections" / "generated_benchmark_macros.tex"


def pct(x: float, digits: int = 0) -> str:
    return f"{100*x:.{digits}f}\\%"


def num(x: float, digits: int = 3) -> str:
    return f"{x:.{digits}f}"


def main() -> None:
    nonlinear = json.loads((RESULTS / "nonlinear_confusion.json").read_text())
    solver = json.loads((RESULTS / "solver_validation.json").read_text())
    gates = json.loads((RESULTS / "gates.json").read_text())
    linear = json.loads((RESULTS / "linear_factorial.json").read_text())

    stable = nonlinear["stable"]
    verdict = nonlinear["verdict"]
    strat = nonlinear["stable_stratified"]
    safety = nonlinear["safety_stable"]

    # Stable-only linear ranking is A=0.25 because the archived linear grid is
    # A in {0.25, 0.30, 0.40}; the latter two are stability-verdict regimes.
    by_design: dict[str, list[float]] = {}
    for row in linear["rows"]:
        if abs(float(row["A"]) - 0.25) < 1e-12:
            by_design.setdefault(row["input"], []).append(float(row["min_pairwise_KL"]))
    stable_linear = {
        k: sum(v) / len(v) for k, v in by_design.items()
    }
    stable_linear = dict(sorted(stable_linear.items(), key=lambda kv: -kv[1]))

    macros = {
        "StableMacro": num(stable["macro_accuracy"]),
        "StableMicro": num(stable["micro_accuracy"]),
        "VerdictMacro": num(verdict["macro_accuracy"]),
        "StableCells": str(stable["n_good"]),
        "StableReplicates": str(stable["n_good"] * nonlinear["reps_per_cell"]),
        "RepsPerCell": str(nonlinear["reps_per_cell"]),
        "SolverN": str(nonlinear["N_solver"]),
        "SolverError": (lambda x: f"{x / (10 ** int(f'{x:.0e}'.split('e')[1])):.2f}\\times 10^{{{int(f'{x:.0e}'.split('e')[1])}}}")(solver["final_err"]),
        "AlphaStarBaseline": f"{gates['alpha_star_0.30']:.16f}",
        "OdeRecall": num(stable["per_class_recall"]["ODE"], 2),
        "CaputoRecall": num(stable["per_class_recall"]["Caputo"], 2),
        "DdeRecall": num(stable["per_class_recall"]["DDE"], 2),
        "LatentRecall": num(stable["per_class_recall"]["latent3"], 2),
        "OdePrecision": num(stable["per_class_precision"]["ODE"], 2),
        "CaputoPrecision": num(stable["per_class_precision"]["Caputo"], 2),
        "DdePrecision": num(stable["per_class_precision"]["DDE"], 2),
        "LatentPrecision": num(stable["per_class_precision"]["latent3"], 2),
        "PrbsAccuracy": num(stable["design_ranking"]["prbs"]),
        "MultisineAccuracy": num(stable["design_ranking"]["multisine"]),
        "SinusoidAccuracy": num(stable["design_ranking"]["sinusoid"]),
        "ChirpAccuracy": num(stable["design_ranking"]["chirp"]),
        "PulseAccuracy": num(stable["design_ranking"]["pulse"]),
        "MultiscaleAccuracy": num(stable["design_ranking"]["multiscale"]),
        "AlphaLowAccuracy": num(strat["by_alpha"]["0.7"], 2),
        "AlphaHighAccuracy": num(strat["by_alpha"]["0.95"], 2),
        "SnrHighAccuracy": num(strat["by_snr"]["hi"], 2),
        "SnrMediumAccuracy": num(strat["by_snr"]["med"], 2),
        "SnrLowAccuracy": num(strat["by_snr"]["lo"], 2),
        "BothAccuracy": num(strat["by_channel"]["both"], 2),
        "PreyAccuracy": num(strat["by_channel"]["prey"], 2),
        "PredAccuracy": num(strat["by_channel"]["pred"], 2),
        "PrbsCrossRate": pct(safety["prbs"]["allee_cross_rate"]),
        "MultisineCrossRate": pct(safety["multisine"]["allee_cross_rate"]),
        "SinusoidCrossRate": pct(safety["sinusoid"]["allee_cross_rate"]),
        "ChirpCrossRate": pct(safety["chirp"]["allee_cross_rate"]),
        "PulseCrossRate": pct(safety["pulse"]["allee_cross_rate"]),
        "MultiscaleCrossRate": pct(safety["multiscale"]["allee_cross_rate"]),
        "PrbsMinMargin": num(safety["prbs"]["min_allee_margin"], 2),
        "MultisineMinMargin": num(safety["multisine"]["min_allee_margin"], 2),
        "SinusoidMinMargin": num(safety["sinusoid"]["min_allee_margin"], 2),
        "ChirpMinMargin": num(safety["chirp"]["min_allee_margin"], 2),
        "PulseMinMargin": num(safety["pulse"]["min_allee_margin"], 2),
        "MultiscaleMinMargin": num(safety["multiscale"]["min_allee_margin"], 2),
        "StableLinearBest": next(iter(stable_linear)),
        "StableLinearBestScore": num(next(iter(stable_linear.values())), 2),
    }

    lines = ["% Auto-generated by benchmark/export_results_tex.py; do not edit by hand."]
    for name, value in macros.items():
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
